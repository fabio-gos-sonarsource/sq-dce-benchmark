// palette + brand colours
var (
	ink     = [3]int{0x22, 0x30, 0x3C}
	mut     = [3]int{0x7A, 0x8A, 0x99}
	grid    = [3]int{0xDD, 0xE4, 0xEA}
	recBg   = [3]int{0xE6, 0xF4, 0xEA}
	rowAlt  = [3]int{0xF4, 0xF7, 0xF9}
	palette = [][3]int{{0xE8, 0x83, 0x3A}, {0x1F, 0x8F, 0xD6}, {0x2F, 0x9E, 0x6E}, {0x9B, 0x59, 0xB6}}
)

const usableW = 178.0 // A4 210mm - 2*16mm margins

func setText(pdf *gofpdf.Fpdf, c [3]int) { pdf.SetTextColor(c[0], c[1], c[2]) }
func setFill(pdf *gofpdf.Fpdf, c [3]int) { pdf.SetFillColor(c[0], c[1], c[2]) }
func setDraw(pdf *gofpdf.Fpdf, c [3]int) { pdf.SetDrawColor(c[0], c[1], c[2]) }

func commas(v float64) string {
	s := fmt.Sprintf("%.0f", v)
	neg := strings.HasPrefix(s, "-")
	if neg {
		s = s[1:]
	}
	var out []byte
	for i, ch := range []byte(s) {
		if i > 0 && (len(s)-i)%3 == 0 {
			out = append(out, ',')
		}
		out = append(out, ch)
	}
	if neg {
		return "-" + string(out)
	}
	return string(out)
}

func mkTr(pdf *gofpdf.Fpdf) func(string) string {
	tr := pdf.UnicodeTranslatorFromDescriptor("")
	rep := strings.NewReplacer("≤", "<=", "≥", ">=", "≈", "~", "→", "->", " ", " ")
	return func(s string) string { return tr(rep.Replace(s)) }
}

func hr(pdf *gofpdf.Fpdf) {
	setDraw(pdf, grid)
	pdf.SetLineWidth(0.3)
	y := pdf.GetY() + 1
	pdf.Line(16, y, 16+usableW, y)
	pdf.SetY(y + 2)
}

func generateReport(cfg *Config, results map[string]Metrics, names []string) {
	if len(names) == 0 {
		die("no results to report")
	}
	pdf := gofpdf.New("P", "mm", "A4", "")
	pdf.SetMargins(16, 14, 16)
	pdf.SetAutoPageBreak(true, 12)
	pdf.AddPage()
	tr := mkTr(pdf)

	// deterministic colours: fewest workers first
	order := append([]string{}, names...)
	sort.SliceStable(order, func(i, j int) bool { return results[order[i]].Workers < results[order[j]].Workers })
	cols := map[string][3]int{}
	for i, n := range order {
		cols[n] = palette[i%len(palette)]
	}

	// ---- title ----
	pdf.SetFont("Helvetica", "B", 18)
	setText(pdf, ink)
	pdf.CellFormat(usableW, 9, tr("SonarQube — Compute Engine throughput benchmark"), "", 1, "L", false, 0, "")
	pdf.SetFont("Helvetica", "", 9)
	setText(pdf, mut)
	pdf.CellFormat(usableW, 5, tr(fmt.Sprintf("Burst of N=%d analyses · seed: %s · replay method", cfg.N, cfg.seedLabel())), "", 1, "L", false, 0, "")
	hr(pdf)

	// ---- comparison table ----
	f1 := func(v float64) string { return fmt.Sprintf("%.1f", v) }
	f0 := func(v float64) string { return fmt.Sprintf("%.0f", v) }
	metricRows := [][]string{{"Metric"}}
	for _, n := range names {
		metricRows[0] = append(metricRows[0], n)
	}
	addM := func(label string, vals ...string) {
		metricRows = append(metricRows, append([]string{label}, vals...))
	}
	col := func(f func(Metrics) string) []string {
		out := make([]string, len(names))
		for i, n := range names {
			out[i] = f(results[n])
		}
		return out
	}
	addM("Workers (detected)", col(func(m Metrics) string {
		if m.WorkersDetail != "" && m.WorkersDetail != "?" {
			return m.WorkersDetail
		}
		return fmt.Sprintf("%d", m.Workers)
	})...)
	addM("Tasks OK", col(func(m Metrics) string { return fmt.Sprintf("%d", m.OK) })...)
	addM("Queue drain (s)", col(func(m Metrics) string { return f0(m.Drain) })...)
	addM("Throughput (tasks/hr)", col(func(m Metrics) string { return f0(m.Thr) })...)
	addM("Avg queue wait (s)", col(func(m Metrics) string { return f1(m.WaitAvg) })...)
	addM("p95 queue wait (s)", col(func(m Metrics) string { return f0(m.WaitP95) })...)
	addM("CE time / task (s)", col(func(m Metrics) string { return f1(m.ProcAvg) })...)

	metricW := 70.0
	tw := (usableW - metricW) / float64(len(names))
	colW := append([]float64{metricW}, repeat(tw, len(names))...)
	drawTable(pdf, tr, colW, metricRows, nil, 9)
	pdf.Ln(3)

	// ---- queue-over-time chart ----
	drawQueueChart(pdf, tr, results, names, cols)
	pdf.Ln(2)
	pdf.SetFont("Helvetica", "", 8.5)
	setText(pdf, mut)
	pdf.MultiCell(usableW, 4, tr("Measured on the customer's instances via the replay method (one scan per target, then N "+
		"instant re-submissions) so the Compute Engine — not the scanner — is the bottleneck. Lower is better on every "+
		"row. A cluster with more workers across nodes drains the queue faster and keeps developer wait low."), "", "L", false)

	// ---- production model ----
	renderModel(pdf, tr, cfg, results, names, cols)

	// ---- footer ----
	pdf.Ln(2)
	hr(pdf)
	pdf.SetFont("Helvetica", "", 8.5)
	setText(pdf, mut)
	pdf.MultiCell(usableW, 4, tr("Non-production benchmark. Load generated by replaying SonarScanner's internal report format "+
		"via api/ce/submit. Ensure both instances run the same version, comparable hardware/DB, and equal per-worker "+
		"CE heap for a fair comparison."), "", "L", false)

	if err := pdf.OutputFileAndClose(cfg.reportPath()); err != nil {
		die("failed to write report: %v", err)
	}
	fmt.Printf("\nReport written: %s\n", cfg.reportPath())
}

func repeat(v float64, n int) []float64 {
	out := make([]float64, n)
	for i := range out {
		out[i] = v
	}
	return out
}

// drawTable renders rows with a dark header, alternating body backgrounds, grid, and
// green-highlighted rows (hi[rowIndex]).
func drawTable(pdf *gofpdf.Fpdf, tr func(string) string, colW []float64, rows [][]string, hi map[int]bool, fs float64) {
	rowH := 6.5
	for ri, row := range rows {
		pdf.SetX(16)
		header := ri == 0
		for ci := range colW {
			cell := ""
			if ci < len(row) {
				cell = row[ci]
			}
			switch {
			case header:
				setFill(pdf, ink)
				setText(pdf, [3]int{255, 255, 255})
				pdf.SetFont("Helvetica", "B", fs)
			case hi[ri]:
				setFill(pdf, recBg)
				setText(pdf, ink)
				pdf.SetFont("Helvetica", "B", fs)
			case (ri-1)%2 == 1:
				setFill(pdf, rowAlt)
				setText(pdf, ink)
				pdf.SetFont("Helvetica", "", fs)
			default:
				setFill(pdf, [3]int{255, 255, 255})
				setText(pdf, ink)
				pdf.SetFont("Helvetica", "", fs)
			}
			setDraw(pdf, grid)
			pdf.SetLineWidth(0.2)
			pdf.CellFormat(colW[ci], rowH, tr(cell), "1", 0, "L", true, 0, "")
		}
		pdf.Ln(rowH)
	}
}

// ---- charts ----

type plot struct {
	pdf              *gofpdf.Fpdf
	x, y, w, h       float64
	xmax, ymax       float64
}

func (p *plot) px(v float64) float64 { return p.x + v/p.xmax*p.w }
func (p *plot) py(v float64) float64 { return p.y + p.h - v/p.ymax*p.h }

func (p *plot) frame(tr func(string) string, title, xlabel, ylabel string, xfmt func(float64) string) {
	pdf := p.pdf
	pdf.SetFont("Helvetica", "B", 10.5)
	setText(pdf, ink)
	pdf.SetXY(p.x, p.y-8)
	pdf.CellFormat(p.w, 5, tr(title), "", 0, "C", false, 0, "")
	setDraw(pdf, grid)
	pdf.SetLineWidth(0.2)
	// horizontal gridlines + y ticks
	pdf.SetFont("Helvetica", "", 8)
	setText(pdf, mut)
	for i := 0; i <= 5; i++ {
		yv := p.ymax * float64(i) / 5
		yy := p.py(yv)
		pdf.Line(p.x, yy, p.x+p.w, yy)
		pdf.SetXY(p.x-14, yy-2)
		pdf.CellFormat(12, 4, fmt.Sprintf("%.0f", yv), "", 0, "R", false, 0, "")
	}
	// x ticks
	for i := 0; i <= 4; i++ {
		xv := p.xmax * float64(i) / 4
		xx := p.px(xv)
		pdf.SetXY(xx-10, p.y+p.h+1)
		pdf.CellFormat(20, 4, tr(xfmt(xv)), "", 0, "C", false, 0, "")
	}
	// axes
	setDraw(pdf, mut)
	pdf.SetLineWidth(0.3)
	pdf.Line(p.x, p.y, p.x, p.y+p.h)
	pdf.Line(p.x, p.y+p.h, p.x+p.w, p.y+p.h)
	// labels
	pdf.SetFont("Helvetica", "", 8.5)
	pdf.SetXY(p.x, p.y+p.h+5)
	pdf.CellFormat(p.w, 4, tr(xlabel), "", 0, "C", false, 0, "")
}

func (p *plot) line(pts [][2]float64, c [3]int, fill bool) {
	pdf := p.pdf
	if fill && len(pts) > 1 {
		poly := []gofpdf.PointType{{X: p.px(pts[0][0]), Y: p.py(0)}}
		for _, pt := range pts {
			poly = append(poly, gofpdf.PointType{X: p.px(pt[0]), Y: p.py(pt[1])})
		}
		poly = append(poly, gofpdf.PointType{X: p.px(pts[len(pts)-1][0]), Y: p.py(0)})
		pdf.SetAlpha(0.12, "Normal")
		setFill(pdf, c)
		pdf.Polygon(poly, "F")
		pdf.SetAlpha(1, "Normal")
	}
	setDraw(pdf, c)
	pdf.SetLineWidth(0.7)
	for i := 1; i < len(pts); i++ {
		pdf.Line(p.px(pts[i-1][0]), p.py(pts[i-1][1]), p.px(pts[i][0]), p.py(pts[i][1]))
	}
}

func (p *plot) legend(tr func(string) string, labels []string, colours [][3]int) {
	pdf := p.pdf
	pdf.SetFont("Helvetica", "", 8.5)
	ly := p.y + 2
	for i, lb := range labels {
		lx := p.x + p.w - 46
		yy := ly + float64(i)*5
		setDraw(pdf, colours[i])
		pdf.SetLineWidth(1.2)
		pdf.Line(lx, yy+1.6, lx+7, yy+1.6)
		setText(pdf, ink)
		pdf.SetXY(lx+9, yy)
		pdf.CellFormat(36, 4, tr(lb), "", 0, "L", false, 0, "")
	}
}

func drawQueueChart(pdf *gofpdf.Fpdf, tr func(string) string, results map[string]Metrics, names []string, cols map[string][3]int) {
	xmax, ymax := 1.0, 1.0
	for _, n := range names {
		s := results[n].Series
		if len(s) > 0 {
			if float64(len(s)-1) > xmax {
				xmax = float64(len(s) - 1)
			}
			for _, v := range s {
				if float64(v) > ymax {
					ymax = float64(v)
				}
			}
		}
	}
	ymax *= 1.12
	p := &plot{pdf: pdf, x: 30, y: pdf.GetY() + 10, w: usableW - 30, h: 52, xmax: xmax, ymax: ymax}
	p.frame(tr, "Queue size over time (measured)", "seconds after burst", "", func(v float64) string { return fmt.Sprintf("%.0f", v) })
	var labels []string
	var lcols [][3]int
	for _, n := range names {
		s := results[n].Series
		if len(s) == 0 {
			continue
		}
		pts := make([][2]float64, len(s))
		for i, v := range s {
			pts[i] = [2]float64{float64(i), float64(v)}
		}
		p.line(pts, cols[n], true)
		labels = append(labels, fmt.Sprintf("%s — %d workers", n, results[n].Workers))
		lcols = append(lcols, cols[n])
	}
	// y-axis label (rotated-ish: placed at top-left)
	pdf.SetFont("Helvetica", "", 8)
	setText(pdf, mut)
	pdf.SetXY(16, p.y-6)
	pdf.CellFormat(30, 4, tr("analyses in queue"), "", 0, "L", false, 0, "")
	p.legend(tr, labels, lcols)
	pdf.SetY(p.y + p.h + 12)
}
